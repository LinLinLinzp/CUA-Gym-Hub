import { statSync } from 'node:fs'
import { resolve } from 'node:path'
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { stateApi } from '../../templates/state-api.js'
import { createInitialData } from './src/data/seed.js'

const endpoint = { host: 'localhost', port: 5418, strictPort: true }

// The Windows sandbox can block esbuild from listing ancestors of the checkout.
// Resolve explicit dependency filenames directly during development.
const resolveWindowsDepFiles = {
  name: 'resolve-windows-dependency-files',
  setup(build) {
    build.onResolve({ filter: /^\.\.?\/.+\.[cm]?js$/ }, ({ path, resolveDir }) => {
      if (!resolveDir) return
      const filename = resolve(resolveDir, path)
      if (statSync(filename, { throwIfNoEntry: false })?.isFile()) return { path: filename }
    })
  },
}

export default defineConfig({
  plugins: [react(), stateApi(createInitialData)],
  optimizeDeps: process.platform === 'win32' ? { esbuildOptions: { plugins: [resolveWindowsDepFiles] } } : undefined,
  server: endpoint,
  preview: endpoint,
})
